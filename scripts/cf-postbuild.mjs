// CloudflareDeployer 不支持 assets / cron：build 后给 .mastra/output/wrangler.json 补
// Workers Static Assets + Cron Trigger，并包一层 entry 增加 scheduled → /cron-tick。
// SPA: apps/web (Vite+React+shadcn) → dist/app.html + assets/*  → /app
import { cpSync, readFileSync, writeFileSync, rmSync, existsSync, mkdirSync } from 'node:fs';
import { execSync } from 'node:child_process';

const out = '.mastra/output';
console.log('[cf-postbuild] building apps/web …');
execSync('npm run build', { cwd: 'apps/web', stdio: 'inherit', env: process.env });

rmSync(`${out}/static`, { recursive: true, force: true });
mkdirSync(`${out}/static`, { recursive: true });
cpSync('apps/web/dist', `${out}/static`, { recursive: true });
if (existsSync('cf-public/index.html')) {
  cpSync('cf-public/index.html', `${out}/static/index.html`);
}
if (existsSync('apps/web/public')) {
  cpSync('apps/web/public', `${out}/static`, { recursive: true });
}

// Wrap default export with scheduled handler that POSTs /cron-tick (PUSH_TOKEN).
const wrapper = `/** Auto-generated by scripts/cf-postbuild.mjs — do not edit. */
import base from './index.orig.mjs';

const cronPath = '/cron-tick';

async function tick(env, ctx) {
  const token = env.PUSH_TOKEN ? String(env.PUSH_TOKEN) : '';
  if (!token) { console.log('[cron] PUSH_TOKEN missing, skip'); return; }
  const baseUrl = String(env.L1_PUBLIC_URL || 'https://mastra-l1.summersmile1984.workers.dev').replace(/\\/$/, '');
  const url = baseUrl + cronPath;
  const req = new Request(url, {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: 'Bearer ' + token, 'x-a2a-notification-token': token },
    body: '{}',
  });
  try {
    const handler = base.fetch || base.default?.fetch || base;
    const res = typeof handler === 'function' ? await handler(req, env, ctx) : await base.fetch(req, env, ctx);
    const text = await res.text().catch(() => '');
    console.log('[cron] tick', res.status, text.slice(0, 200));
  } catch (e) {
    console.log('[cron] tick failed', String(e?.message ?? e).slice(0, 200));
  }
}

const worker = {
  async fetch(request, env, ctx) {
    const h = base.fetch || base.default?.fetch || base;
    return typeof h === 'function' ? h(request, env, ctx) : base.fetch(request, env, ctx);
  },
  async scheduled(controller, env, ctx) {
    ctx.waitUntil(tick(env, ctx));
  },
};

export default worker;
`;

// rename original entry then write wrapper as index.mjs
const orig = `${out}/index.orig.mjs`;
const idx = `${out}/index.mjs`;
if (existsSync(idx)) {
  // avoid double-wrap on rebuild without clean
  const cur = readFileSync(idx, 'utf8');
  if (!cur.includes('Auto-generated by scripts/cf-postbuild')) {
    writeFileSync(orig, cur);
  } else if (!existsSync(orig)) {
    throw new Error('index.mjs already wrapped but index.orig.mjs missing — clean .mastra/output and rebuild');
  }
}
writeFileSync(idx, wrapper);

const f = `${out}/wrangler.json`;
const w = JSON.parse(readFileSync(f, 'utf8'));
w.assets = { directory: './static', html_handling: 'auto-trailing-slash', not_found_handling: 'none' };
w.triggers = { crons: ['* * * * *'] }; // every minute → scheduled → /cron-tick
w.main = './index.mjs';
// point D1 migrations at repo migrations/ (path relative to wrangler.json location = .mastra/output)
w.d1_databases = (w.d1_databases || []).map((d) => ({ ...d, migrations_dir: '../../migrations' }));
// CF memory bindings (Workers AI embeddings + Vectorize semantic recall); idempotent if deployer already emitted them
w.ai = w.ai || { binding: 'AI' };
w.vectorize = w.vectorize?.length ? w.vectorize : [{ binding: 'VECTORIZE', index_name: 'mastra-l1-memory' }];
writeFileSync(f, JSON.stringify(w, null, 2));
console.log('[cf-postbuild] assets + cron (* * * * *) + scheduled wrapper → ./index.mjs');
